using Orca.Core.Config;
using Orca.Core.Domain;
using Orca.Core.Execution;
using Orca.Core.Planning;

namespace Orca.Tests;

/// <summary>SUG-01's Scout stage inside the single-candidate strategy: when it runs, what
/// it feeds the Planner, the read-only tree-fingerprint guard, reuse of an existing
/// audit, and the skip paths. Fake executor — no process spawns, no quota. The repo is a
/// real git repo (the guard hashes its tree); the vault is a plain temp dir.</summary>
public sealed class ScoutStageTests : IDisposable
{
    private readonly TempGitRepo _repo = new();
    private readonly string _vault = Directory.CreateTempSubdirectory("orca-scout-vault-").FullName;

    public ScoutStageTests()
    {
        // Real runs are guaranteed this before planning spends anything
        // (OrcaIgnore.EnsureIgnored gates plan-generate); the tree-fingerprint guard
        // relies on it to see the Scout's writes, not Orca's own state writes.
        File.WriteAllText(Path.Combine(_repo.Root, ".gitignore"), ".orca/\n");
        _repo.Git("add", "-A");
        _repo.Git("commit", "-m", "ignore .orca");
    }

    public void Dispose()
    {
        _repo.Dispose();
        Directory.Delete(_vault, recursive: true);
    }

    private OrcaConfig Config(bool withScout = true) => new()
    {
        RepoConfigPath = Path.Combine(_repo.Root, "orca.json"),
        GlobalConfigPath = Path.Combine(_repo.Root, "global.json"),
        VaultRoot = _vault,
        VaultName = "test-vault",
        PlansDir = "Plans",
        BuildCommand = ["dotnet", "build"],
        TestCommand = ["dotnet", "test"],
        GateTimeout = null,
        MaxParseRetries = 1,
        MaxCheckpointAttempts = null,
        PlanningCandidates = null,
        DeniedTools = [],
        RoleSections = new RolesSection
        {
            Planner = new RoleSection
            {
                AllowedTools = ["Read", "Write", "Edit"],
                MaxTurns = 30,
                TimeoutSeconds = 600,
            },
            Scout = withScout
                ? new RoleSection
                {
                    AllowedTools = ["Read", "Glob", "Grep", "Write", "Bash(git log*)"],
                    MaxTurns = 40,
                    TimeoutSeconds = 900,
                    Model = "sonnet",
                }
                : null,
        },
    };

    private static PlanningRequest Request(bool noScout = false) => new()
    {
        PlanId = "recipe-tagging",
        Goal = "Add tag support to recipes.",
        Title = null,
        TargetRepoName = "RecipeApp",
        BaseBranch = "main",
        NoScout = noScout,
    };

    private string AuditPath => Path.Combine(_vault, "Plans", "recipe-tagging", "recipe-tagging.audit.md");
    private string PlanPath => Path.Combine(_vault, "Plans", "recipe-tagging", "recipe-tagging.md");

    private const string AuditText =
        """
        ---
        schema_version: 1
        type: audit
        plan_id: recipe-tagging
        created: 2026-07-17T09:00:00Z
        ---

        ## Verified current state

        Tags are absent (checked src/Db).

        ## Key files and patterns

        Controllers under src/Api.

        ## Dependencies

        EF Core 10.

        ## Risks

        None seen; looked at src and tests.

        ## Suggested checkpoint boundaries

        Entity first, then endpoints.
        """;

    private static string ValidPlanText() => """
        ---
        schema_version: 1
        plan_id: recipe-tagging
        plan_version: 1
        title: "Recipe tagging"
        status: draft
        target_repo: "RecipeApp"
        base_branch: "main"
        created: 2026-07-06T21:10:00Z
        updated: 2026-07-06T21:10:00Z
        planning:
          strategy: single_candidate
        checkpoints:
          - id: 01-tag-entity
            description: Add the Tag entity
            status: pending
            acceptance_criteria:
              - Tag entity exists
        ---

        ## Context

        Generated by the fake planner.
        """;

    private void WriteVaultFile(string path, string text)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, text);
    }

    private SingleCandidatePlanningStrategy Strategy(FakeExecutor executor, bool withScout = true) =>
        new(Config(withScout), executor, _repo.Root);

    [Fact]
    public void Prepare_without_a_scout_config_plans_goal_only_as_before()
    {
        var preview = Strategy(new FakeExecutor(), withScout: false).Prepare(Request());

        Assert.Null(preview.Scout);
        Assert.Contains("not configured", preview.ScoutSkipReason);
        Assert.DoesNotContain("## Repository audit (Scout)", preview.Prompt);
    }

    [Fact]
    public void Prepare_honors_no_scout()
    {
        var preview = Strategy(new FakeExecutor()).Prepare(Request(noScout: true));

        Assert.Null(preview.Scout);
        Assert.Contains("--no-scout", preview.ScoutSkipReason);
    }

    [Fact]
    public void Prepare_reuses_an_existing_valid_audit_and_embeds_it_now()
    {
        WriteVaultFile(AuditPath, AuditText);

        var preview = Strategy(new FakeExecutor()).Prepare(Request());

        Assert.Null(preview.Scout);
        Assert.Contains("reusing", preview.ScoutSkipReason);
        Assert.Contains("## Repository audit (Scout)", preview.Prompt);
        Assert.Contains("Tags are absent", preview.Prompt);
    }

    [Fact]
    public void Prepare_plans_a_scout_stage_with_the_repo_as_cwd_and_the_absolute_audit_path()
    {
        var preview = Strategy(new FakeExecutor()).Prepare(Request());

        Assert.NotNull(preview.Scout);
        Assert.Null(preview.ScoutSkipReason);
        Assert.Equal(_repo.Root, preview.Scout.Options.WorkingDirectory);
        Assert.Equal("sonnet", preview.Scout.Options.Model);
        Assert.Equal(AuditPath, preview.Scout.AuditFilePath);
        Assert.Contains(AuditPath, preview.Scout.Prompt);
    }

    [Fact]
    public async Task Scout_runs_first_and_the_planner_prompt_gains_the_audit()
    {
        var executor = new FakeExecutor();
        executor.Enqueue(FakeExecutor.Success, () => WriteVaultFile(AuditPath, AuditText));
        executor.Enqueue(FakeExecutor.Success, () => WriteVaultFile(PlanPath, ValidPlanText()));
        var strategy = Strategy(executor);

        var outcome = await strategy.GenerateAsync(strategy.Prepare(Request()));

        Assert.Equal(PlanningRunStatus.Succeeded, outcome.State.Status);
        Assert.Equal(2, executor.Invocations.Count);
        Assert.Equal(_repo.Root, executor.Invocations[0].Options.WorkingDirectory);
        Assert.Equal(_vault, executor.Invocations[1].Options.WorkingDirectory);
        Assert.Contains("## Repository audit (Scout)", executor.Invocations[1].Options.Prompt);
        Assert.Contains("Tags are absent", executor.Invocations[1].Options.Prompt);

        Assert.Equal(2, outcome.State.Attempts.Count);
        Assert.Equal("scout", outcome.State.Attempts[0].Role);
        Assert.Equal("planner", outcome.State.Attempts[1].Role);
        Assert.Equal(ScoutPrompt.RoleSha256, outcome.State.PromptFileHashes["scout"]);
    }

    [Fact]
    public async Task A_scout_that_modifies_the_repo_fails_the_run_loudly()
    {
        var executor = new FakeExecutor();
        executor.Enqueue(FakeExecutor.Success, () =>
        {
            File.WriteAllText(Path.Combine(_repo.Root, "stray.txt"), "oops\n");
            WriteVaultFile(AuditPath, AuditText);
        });
        var strategy = Strategy(executor);

        var outcome = await strategy.GenerateAsync(strategy.Prepare(Request()));

        Assert.Equal(PlanningRunStatus.Failed, outcome.State.Status);
        Assert.Contains("modified the target repository", outcome.FailureDetail);
        Assert.Single(executor.Invocations); // the Planner never ran, nothing more spent
    }

    [Fact]
    public async Task Scout_parse_failures_retry_then_exhaust_the_ceiling()
    {
        var executor = new FakeExecutor();
        executor.Enqueue(FakeExecutor.Success, () => WriteVaultFile(AuditPath, "not an audit"));
        executor.Enqueue(FakeExecutor.Success, () => WriteVaultFile(AuditPath, "still not an audit"));
        var strategy = Strategy(executor);

        var outcome = await strategy.GenerateAsync(strategy.Prepare(Request()));

        Assert.Equal(PlanningRunStatus.Failed, outcome.State.Status);
        Assert.Contains("exhausting maxParseRetries", outcome.FailureDetail);
        Assert.Equal(2, executor.Invocations.Count);
        Assert.Contains("Retry — your previous output failed validation", executor.Invocations[1].Options.Prompt);
    }

    private sealed class FakeExecutor : IClaudeExecutor
    {
        public List<(ClaudeInvocationOptions Options, RunLogPaths LogPaths)> Invocations { get; } = [];

        private readonly Queue<(ClaudeExecutionResult Result, Action? SideEffect)> _script = new();

        public void Enqueue(ClaudeExecutionResult result, Action? sideEffect) =>
            _script.Enqueue((result, sideEffect));

        public Task<ClaudeExecutionResult> ExecuteAsync(
            ClaudeInvocationOptions options, RunLogPaths logPaths,
            IClaudeStreamObserver? observer = null, CancellationToken cancellationToken = default)
        {
            Invocations.Add((options, logPaths));
            if (_script.Count == 0)
                throw new InvalidOperationException("fake executor invoked more times than scripted");
            var (result, sideEffect) = _script.Dequeue();
            sideEffect?.Invoke();
            return Task.FromResult(result);
        }

        public static ClaudeExecutionResult Success { get; } = new()
        {
            Outcome = ExecutionOutcome.Completed,
            ExitCode = 0,
            SessionId = "fake-session",
            Result = new ClaudeResultSummary
            {
                Subtype = "success",
                IsError = false,
                SessionId = "fake-session",
                NumTurns = 3,
                DurationMs = 1500,
                TotalCostUsd = 0.25m,
                Usage = new TokenUsage
                {
                    InputTokens = 100,
                    OutputTokens = 50,
                    CacheCreationInputTokens = 0,
                    CacheReadInputTokens = 0,
                },
                ResultText = null,
            },
            Elapsed = TimeSpan.FromSeconds(2),
        };
    }
}
