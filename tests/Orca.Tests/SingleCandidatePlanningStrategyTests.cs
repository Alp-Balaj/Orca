using Orca.Core.Config;
using Orca.Core.Domain;
using Orca.Core.Execution;
using Orca.Core.Planning;

namespace Orca.Tests;

/// <summary>Orchestration of the single-candidate Planner against a fake executor: the
/// capped Reflexion parse-retry (spec §5.4), the no-auto-retry rule for invocation-level
/// failures, and resume-with-continued-numbering (the owner-approved rate-limit/auth
/// contract). No process spawns, no quota.</summary>
public sealed class SingleCandidatePlanningStrategyTests : IDisposable
{
    private readonly string _repo = Directory.CreateTempSubdirectory("orca-planning-repo-").FullName;
    private readonly string _vault = Directory.CreateTempSubdirectory("orca-planning-vault-").FullName;

    public void Dispose()
    {
        Directory.Delete(_repo, recursive: true);
        Directory.Delete(_vault, recursive: true);
    }

    private OrcaConfig Config(int? maxParseRetries = 1) => new()
    {
        RepoConfigPath = Path.Combine(_repo, "orca.json"),
        GlobalConfigPath = Path.Combine(_repo, "global.json"),
        VaultRoot = _vault,
        VaultName = "test-vault",
        PlansDir = "Plans",
        BuildCommand = ["dotnet", "build"],
        TestCommand = ["dotnet", "test"],
        MaxParseRetries = maxParseRetries,
        MaxCheckpointAttempts = null,
        PlanningCandidates = null,
        DeniedTools = ["Bash(git push*)"],
        RoleSections = new RolesSection
        {
            Planner = new RoleSection
            {
                AllowedTools = ["Read", "Write", "Edit"],
                MaxTurns = 30,
                TimeoutSeconds = 600,
            },
        },
    };

    private static PlanningRequest Request() => new()
    {
        PlanId = "recipe-tagging",
        Goal = "Add tag support to recipes with filtering in the list view",
        Title = null,
        TargetRepoName = "RecipeApp",
        BaseBranch = "main",
    };

    private string PlanPath => Path.Combine(_vault, "Plans", "recipe-tagging", "recipe-tagging.md");

    private static string ValidPlanText(string status = "draft") => $"""
        ---
        schema_version: 1
        plan_id: recipe-tagging
        plan_version: 1
        title: "Recipe tagging"
        status: {status}
        target_repo: "RecipeApp"
        base_branch: "main"
        created: 2026-07-06T21:10:00Z
        updated: 2026-07-06T21:10:00Z
        planning:
          strategy: single_candidate
        checkpoints:
          - id: 01-tag-entity
            description: Add the Tag entity
            status: pending
            acceptance_criteria:
              - Tag entity exists
        ---

        ## Context

        Generated by the fake planner.
        """;

    private SingleCandidatePlanningStrategy Strategy(FakePlannerExecutor executor, int? maxParseRetries = 1) =>
        new(Config(maxParseRetries), executor, _repo);

    private void WritePlanFile(string text)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(PlanPath)!);
        File.WriteAllText(PlanPath, text);
    }

    [Fact]
    public async Task Success_first_try_returns_the_parsed_plan_and_persists_state()
    {
        var executor = new FakePlannerExecutor();
        executor.Enqueue(FakePlannerExecutor.Success, () => WritePlanFile(ValidPlanText()));
        var strategy = Strategy(executor);

        var preview = strategy.Prepare(Request());
        var outcome = await strategy.GenerateAsync(preview);

        Assert.Equal(PlanningRunStatus.Succeeded, outcome.State.Status);
        Assert.NotNull(outcome.Plan);
        Assert.Equal("recipe-tagging", outcome.Plan.PlanId);
        Assert.Null(outcome.FailureDetail);

        var attempt = Assert.Single(outcome.State.Attempts);
        Assert.Equal(InvocationStopReason.Succeeded, attempt.StopReason);
        Assert.Null(attempt.ParseFailure);
        Assert.Equal(0.25m, attempt.CostUsd);
        Assert.Equal(PlannerPrompt.RoleSha256, outcome.State.PromptFileHashes["planner"]);

        // Persisted, and re-readable, exactly where the approved schema says.
        var stored = new PlanningStateStore(_repo).Read("recipe-tagging");
        Assert.Equal(PlanningRunStatus.Succeeded, stored!.Status);
    }

    [Fact]
    public async Task The_invocation_is_vault_scoped_with_the_planner_role_settings()
    {
        var executor = new FakePlannerExecutor();
        executor.Enqueue(FakePlannerExecutor.Success, () => WritePlanFile(ValidPlanText()));
        var strategy = Strategy(executor);

        var preview = strategy.Prepare(Request());
        await strategy.GenerateAsync(preview);

        var options = Assert.Single(executor.Invocations).Options;
        Assert.Equal(_vault, options.WorkingDirectory);
        Assert.Equal(["Read", "Write", "Edit"], options.AllowedTools);
        Assert.Equal(30, options.MaxTurns);

        // The deny payload is written beside the attempt's logs as input evidence.
        Assert.NotNull(options.SettingsFilePath);
        Assert.EndsWith("planning.attempt-1.settings.json", options.SettingsFilePath);
        Assert.Contains("Bash(git push*)", File.ReadAllText(options.SettingsFilePath!));

        // And the prompt carries the request block.
        Assert.Contains("recipe-tagging", options.Prompt);
        Assert.Contains("Plans/recipe-tagging/recipe-tagging.md", options.Prompt);
        Assert.Contains("Add tag support to recipes", options.Prompt);
        Assert.DoesNotContain("## Retry", options.Prompt);
    }

    [Fact]
    public async Task Parse_failure_feeds_the_exact_error_into_a_capped_retry()
    {
        var executor = new FakePlannerExecutor();
        // First attempt self-approves — a GeneratedPlanRules violation, same retry path
        // as a parser rejection.
        executor.Enqueue(FakePlannerExecutor.Success, () => WritePlanFile(ValidPlanText(status: "approved")));
        executor.Enqueue(FakePlannerExecutor.Success, () => WritePlanFile(ValidPlanText()));
        var strategy = Strategy(executor, maxParseRetries: 1);

        var outcome = await strategy.GenerateAsync(strategy.Prepare(Request()));

        Assert.Equal(PlanningRunStatus.Succeeded, outcome.State.Status);
        Assert.Equal(2, executor.Invocations.Count);
        Assert.Equal(2, outcome.State.Attempts.Count);

        var firstFailure = outcome.State.Attempts[0].ParseFailure;
        Assert.NotNull(firstFailure);
        Assert.Contains("draft", firstFailure);
        // The retry prompt carries the exact error and the fix-in-place instruction.
        var retryPrompt = executor.Invocations[1].Options.Prompt;
        Assert.Contains("## Retry", retryPrompt);
        Assert.Contains(firstFailure, retryPrompt);
        // Fresh invocation, fresh evidence paths — never --resume, never overwrite.
        Assert.EndsWith("planning.attempt-1.ndjson", executor.Invocations[0].LogPaths.EventLog);
        Assert.EndsWith("planning.attempt-2.ndjson", executor.Invocations[1].LogPaths.EventLog);
    }

    [Fact]
    public async Task Retry_exhaustion_fails_with_the_last_error_and_leaves_the_file()
    {
        var executor = new FakePlannerExecutor();
        executor.Enqueue(FakePlannerExecutor.Success, () => WritePlanFile("not a plan at all"));
        var strategy = Strategy(executor, maxParseRetries: 0);

        var outcome = await strategy.GenerateAsync(strategy.Prepare(Request()));

        Assert.Equal(PlanningRunStatus.Failed, outcome.State.Status);
        Assert.Null(outcome.Plan);
        Assert.Single(executor.Invocations);
        Assert.Contains("maxParseRetries=0", outcome.FailureDetail);
        // The rejected file stays for inspection.
        Assert.True(File.Exists(PlanPath));
    }

    [Fact]
    public async Task A_planner_that_writes_nothing_is_a_parse_failure_not_a_crash()
    {
        var executor = new FakePlannerExecutor();
        executor.Enqueue(FakePlannerExecutor.Success, sideEffect: null);
        var strategy = Strategy(executor, maxParseRetries: 0);

        var outcome = await strategy.GenerateAsync(strategy.Prepare(Request()));

        Assert.Equal(PlanningRunStatus.Failed, outcome.State.Status);
        Assert.Contains("wrote no file", outcome.FailureDetail);
    }

    [Fact]
    public async Task Invocation_failures_stop_loudly_and_are_never_retried()
    {
        var executor = new FakePlannerExecutor();
        executor.Enqueue(FakePlannerExecutor.AuthFailed, sideEffect: null);
        var strategy = Strategy(executor, maxParseRetries: 5);

        var outcome = await strategy.GenerateAsync(strategy.Prepare(Request()));

        Assert.Equal(PlanningRunStatus.Failed, outcome.State.Status);
        Assert.Single(executor.Invocations); // retries are for parse failures only
        var attempt = Assert.Single(outcome.State.Attempts);
        Assert.Equal(InvocationStopReason.AuthFailed, attempt.StopReason);
        Assert.Null(attempt.ParseFailure);
        Assert.Equal("Not logged in · Please run /login", outcome.FailureDetail);
    }

    [Fact]
    public async Task Rate_limited_run_resumes_later_with_continued_numbering()
    {
        var executor = new FakePlannerExecutor();
        executor.Enqueue(FakePlannerExecutor.RateLimited, sideEffect: null);
        var strategy = Strategy(executor);
        var first = await strategy.GenerateAsync(strategy.Prepare(Request()));

        Assert.Equal(PlanningRunStatus.Failed, first.State.Status);
        Assert.Equal(InvocationStopReason.RateLimited, first.State.Attempts[^1].StopReason);

        // Later, quota restored: the human re-runs. Numbering continues; the prompt is
        // the initial shape again — there is no parse error to correct.
        var resumed = new FakePlannerExecutor();
        resumed.Enqueue(FakePlannerExecutor.Success, () => WritePlanFile(ValidPlanText()));
        var retryStrategy = Strategy(resumed);
        var preview = retryStrategy.Prepare(Request());

        Assert.Equal(2, preview.Attempt);
        Assert.DoesNotContain("## Retry", preview.Prompt);

        var outcome = await retryStrategy.GenerateAsync(preview);

        Assert.Equal(PlanningRunStatus.Succeeded, outcome.State.Status);
        Assert.Equal([1, 2], outcome.State.Attempts.Select(a => a.Attempt));
        Assert.Equal(0.25m, outcome.State.AccumulatedCostUsd);
    }

    [Fact]
    public async Task Resume_after_a_recorded_parse_failure_re_enters_the_retry_conversation()
    {
        var executor = new FakePlannerExecutor();
        executor.Enqueue(FakePlannerExecutor.Success, () => WritePlanFile("still not a plan"));
        await Strategy(executor, maxParseRetries: 0).GenerateAsync(
            Strategy(executor, maxParseRetries: 0).Prepare(Request()));

        var preview = Strategy(new FakePlannerExecutor()).Prepare(Request());

        Assert.Equal(2, preview.Attempt);
        Assert.Contains("## Retry", preview.Prompt);
        Assert.Contains("frontmatter", preview.Prompt); // the recorded parser error rides along
    }

    [Fact]
    public void Refuses_a_plan_file_no_planning_state_claims()
    {
        WritePlanFile(ValidPlanText());

        var e = Assert.Throws<PlanningException>(() =>
            Strategy(new FakePlannerExecutor()).Prepare(Request()));

        Assert.Contains("no planning state claims it", e.Message);
    }

    [Fact]
    public async Task Refuses_to_regenerate_over_a_succeeded_run()
    {
        var executor = new FakePlannerExecutor();
        executor.Enqueue(FakePlannerExecutor.Success, () => WritePlanFile(ValidPlanText()));
        var strategy = Strategy(executor);
        await strategy.GenerateAsync(strategy.Prepare(Request()));

        var e = Assert.Throws<PlanningException>(() =>
            Strategy(new FakePlannerExecutor()).Prepare(Request()));

        Assert.Contains("already succeeded", e.Message);
    }

    [Fact]
    public void Requires_the_parse_retry_ceiling_from_config()
    {
        var e = Assert.Throws<ConfigException>(() =>
            Strategy(new FakePlannerExecutor(), maxParseRetries: null).Prepare(Request()));

        Assert.Contains("maxParseRetries", e.Message);
    }

    [Fact]
    public void A_crashed_attempts_orphan_log_is_skipped_never_overwritten()
    {
        // A stream-parse crash can leave a log file no state ever recorded; run logs are
        // append-only evidence, so numbering skips past them.
        var orphan = Path.Combine(_repo, ".orca", "runs", "recipe-tagging", "planning.attempt-1.ndjson");
        Directory.CreateDirectory(Path.GetDirectoryName(orphan)!);
        File.WriteAllText(orphan, "orphaned evidence");

        var preview = Strategy(new FakePlannerExecutor()).Prepare(Request());

        Assert.Equal(2, preview.Attempt);
        Assert.Equal("orphaned evidence", File.ReadAllText(orphan));
    }

    [Fact]
    public void Prepare_mutates_nothing()
    {
        Strategy(new FakePlannerExecutor()).Prepare(Request());

        Assert.Null(new PlanningStateStore(_repo).Read("recipe-tagging"));
        Assert.False(File.Exists(PlanPath));
        Assert.False(Directory.Exists(Path.Combine(_repo, ".orca", "runs")));
    }

    /// <summary>Stands in for the claude process: dequeues one scripted behavior per
    /// invocation — a canned result plus an optional vault side effect. No process, no
    /// quota.</summary>
    private sealed class FakePlannerExecutor : IClaudeExecutor
    {
        public List<(ClaudeInvocationOptions Options, RunLogPaths LogPaths)> Invocations { get; } = [];

        private readonly Queue<(ClaudeExecutionResult Result, Action? SideEffect)> _script = new();

        public void Enqueue(ClaudeExecutionResult result, Action? sideEffect) =>
            _script.Enqueue((result, sideEffect));

        public Task<ClaudeExecutionResult> ExecuteAsync(
            ClaudeInvocationOptions options, RunLogPaths logPaths, CancellationToken cancellationToken = default)
        {
            Invocations.Add((options, logPaths));
            if (_script.Count == 0)
                throw new InvalidOperationException("fake executor invoked more times than scripted");
            var (result, sideEffect) = _script.Dequeue();
            sideEffect?.Invoke();
            return Task.FromResult(result);
        }

        public static ClaudeExecutionResult Success { get; } = new()
        {
            Outcome = ExecutionOutcome.Completed,
            ExitCode = 0,
            SessionId = "fake-session",
            Result = Summary(isError: false, "success", text: null),
            Elapsed = TimeSpan.FromSeconds(2),
        };

        public static ClaudeExecutionResult AuthFailed { get; } = new()
        {
            Outcome = ExecutionOutcome.Completed,
            ExitCode = 1,
            SessionId = "fake-session",
            Result = Summary(isError: true, "success", "Not logged in · Please run /login"),
            AuthenticationFailed = true,
            Elapsed = TimeSpan.FromSeconds(1),
        };

        public static ClaudeExecutionResult RateLimited { get; } = new()
        {
            Outcome = ExecutionOutcome.Completed,
            ExitCode = 1,
            SessionId = "fake-session",
            Result = Summary(isError: true, "success", text: null),
            LastRateLimit = new RateLimitInfo { Status = "rejected", ResetsAt = 1783361400 },
            Elapsed = TimeSpan.FromSeconds(1),
        };

        private static ClaudeResultSummary Summary(bool isError, string subtype, string? text) => new()
        {
            Subtype = subtype,
            IsError = isError,
            SessionId = "fake-session",
            NumTurns = 3,
            DurationMs = 1500,
            TotalCostUsd = isError ? 0m : 0.25m,
            Usage = new TokenUsage
            {
                InputTokens = 100,
                OutputTokens = 50,
                CacheCreationInputTokens = 0,
                CacheReadInputTokens = 0,
            },
            ResultText = text,
        };
    }
}
