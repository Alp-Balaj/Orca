using System.Globalization;
using System.Text;
using Orca.Core.Config;
using Orca.Core.Domain;
using Orca.Core.Execution;
using Orca.Core.Git;
using Orca.Core.Vault;

namespace Orca.Core.Run;

/// <summary>An approved checkpoint branch the base branch doesn't contain yet — the
/// classic owed loose end ("merge it before its dependents run").</summary>
public sealed record UnmergedApproval(string PlanId, string CheckpointId, string Branch, string BaseBranch);

/// <summary>Composes the auto-maintained Dashboard note (SUG-07) from status-report
/// evidence — the cockpit note the owner already writes by hand, generated instead.
/// Pure text projection; the writer below owns paths and I/O. Generated, never
/// authoritative: the banner says so and the plan files stay the source of truth.</summary>
public static class DashboardComposer
{
    public const string Marker = "AI-generated by Orca — do not hand-edit.";

    public static string Compose(
        StatusReport report, IReadOnlyList<UnmergedApproval> unmergedApprovals, DateTimeOffset now)
    {
        var sb = new StringBuilder();
        sb.Append("---\n");
        sb.Append("type: dashboard\n");
        sb.Append($"project: {Path.GetFileName(report.RepoRoot)}\n");
        sb.Append($"updated: {now.ToUniversalTime():yyyy-MM-ddTHH:mm:ss}Z\n");
        sb.Append("---\n\n");
        sb.Append($"> [!warning] {Marker}\n");
        sb.Append("> Regenerated after checkpoint decisions and by `orca status --write-dashboard`. ");
        sb.Append("The per-plan files remain the source of truth.\n\n");

        sb.Append("## Focus right now\n\n");
        sb.Append(FocusLine(report, unmergedApprovals)).Append("\n\n");

        AppendNextUp(sb, report);
        AppendLooseEnds(sb, report, unmergedApprovals, now);
        AppendSpend(sb, report);

        return sb.ToString();
    }

    /// <summary>The single next action, by descending urgency: a failed/interrupted last
    /// attempt to pick back up, the first runnable checkpoint, a draft plan awaiting
    /// review, an unmerged approval, or "all quiet".</summary>
    private static string FocusLine(StatusReport report, IReadOnlyList<UnmergedApproval> unmerged)
    {
        foreach (var entry in report.Plans)
        {
            if (entry.Plan.Status is not (PlanStatus.Approved or PlanStatus.InProgress))
                continue;
            if (entry.RunState is { LastStopReason: { } reason } state
                && reason != InvocationStopReason.Succeeded)
                return $"pick up [[{entry.Plan.PlanId}]] — attempt {state.Attempt} of `{state.CheckpointId}` " +
                       $"stopped {InvocationStopReasons.ToWire(reason)}; re-run checkpoint-run to resume.";
        }

        foreach (var entry in report.Plans)
        {
            if (entry.Plan.Status is not (PlanStatus.Approved or PlanStatus.InProgress))
                continue;
            var next = NextStepAdvice.NextPending(entry.Plan);
            if (next is not null)
                return $"run `{next.Id}` of [[{entry.Plan.PlanId}]] — {next.Description}";
        }

        var draft = report.Plans.FirstOrDefault(p => p.Plan.Status == PlanStatus.Draft);
        if (draft is not null)
            return $"review and approve [[{draft.Plan.PlanId}]] — it is still a draft; nothing runs against a draft.";

        if (unmerged.Count > 0)
            return $"merge `{unmerged[0].Branch}` into `{unmerged[0].BaseBranch}` — approved work the base branch doesn't have yet.";

        return "all quiet — every plan is complete or closed; plan the next goal.";
    }

    private static void AppendNextUp(StringBuilder sb, StatusReport report)
    {
        sb.Append("## Next up\n\n");
        var any = false;
        foreach (var entry in report.Plans)
        {
            if (entry.Plan.Status is not (PlanStatus.Approved or PlanStatus.InProgress))
                continue;
            var next = NextStepAdvice.NextPending(entry.Plan);
            if (next is null)
                continue;
            any = true;
            sb.Append($"- [[{entry.Plan.PlanId}]] → `{next.Id}` — {next.Description}\n");
        }

        if (!any)
            sb.Append("- (nothing runnable — see loose ends)\n");
        sb.Append('\n');
    }

    private static void AppendLooseEnds(
        StringBuilder sb, StatusReport report, IReadOnlyList<UnmergedApproval> unmerged, DateTimeOffset now)
    {
        sb.Append("## Owed loose ends\n\n");
        var any = false;

        foreach (var item in unmerged)
        {
            any = true;
            sb.Append($"- [[{item.PlanId}]]: `{item.CheckpointId}` is approved on `{item.Branch}` ");
            sb.Append($"but not merged into `{item.BaseBranch}` — merge before its dependents run.\n");
        }

        foreach (var entry in report.Plans)
        {
            foreach (var checkpoint in entry.Plan.Checkpoints)
            {
                // Evidence-vs-status drift: a passing latest verification while the plan
                // file still says pending — almost always a forgotten mark-complete.
                if (checkpoint.Status == CheckpointStatus.Pending
                    && entry.Evidence.TryGetValue(checkpoint.Id, out var evidence)
                    && evidence.LatestVerification is { Verdict: VerificationVerdict.Pass } verification)
                {
                    any = true;
                    sb.Append($"- [[{entry.Plan.PlanId}]]: `{checkpoint.Id}` has a passing verification ");
                    sb.Append($"(attempt {verification.Attempt}) but the plan file still says pending — ");
                    sb.Append("mark it complete or deliberately re-run it.\n");
                }
            }

            if (entry.Plan.Status == PlanStatus.Draft)
            {
                var age = (now - entry.Plan.Updated).Days;
                if (age >= 2)
                {
                    any = true;
                    sb.Append($"- [[{entry.Plan.PlanId}]] has been a draft for {age} days — approve it or abandon it.\n");
                }
            }
        }

        if (!any)
            sb.Append("- (none detected)\n");
        sb.Append('\n');
    }

    private static void AppendSpend(StringBuilder sb, StatusReport report)
    {
        sb.Append("## Spend\n\n");
        sb.Append("| plan | status | accumulated cost | last usage (in/out) |\n");
        sb.Append("| --- | --- | --- | --- |\n");
        foreach (var entry in report.Plans)
        {
            var cost = entry.RunState is { } state
                ? "$" + state.AccumulatedCostUsd.ToString("0.00", CultureInfo.InvariantCulture)
                : "—";
            var usage = entry.RunState?.LastUsage is { } u
                ? $"{u.InputTokens:N0}/{u.OutputTokens:N0}"
                : "—";
            sb.Append($"| [[{entry.Plan.PlanId}]] | {SchemaEnums.ToYaml(entry.Plan.Status)} | {cost} | {usage} |\n");
        }

        sb.Append('\n');
    }
}

/// <summary>Owns the dashboard's location and I/O: <c>Dashboard.md</c> as a SIBLING of
/// the plans directory (the project folder your hand-written one lives in), full
/// regenerate-in-place, atomic write. <see cref="TryWrite"/> never throws — a dashboard
/// is a convenience view and must never block or fail a run (SUG-07's third rule).</summary>
public static class DashboardWriter
{
    public static string PathFor(OrcaConfig config)
    {
        var layout = new VaultLayout(config.VaultRoot, config.PlansDir);
        return Path.Combine(Path.GetDirectoryName(layout.PlansRoot)!, "Dashboard.md");
    }

    /// <summary>Regenerates the dashboard from fresh evidence. Returns the path written,
    /// or null with <paramref name="warning"/> set — callers surface the warning (or
    /// ignore it, in the TUI) and always continue.</summary>
    public static string? TryWrite(OrcaConfig config, GitWorkspace workspace, out string? warning)
    {
        try
        {
            var report = StatusReportBuilder.Build(config, workspace, planId: null);
            var text = DashboardComposer.Compose(
                report, CollectUnmergedApprovals(report, workspace), DateTimeOffset.UtcNow);

            var path = PathFor(config);
            var tempPath = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
            try
            {
                File.WriteAllText(tempPath, text);
                File.Move(tempPath, path, overwrite: true);
            }
            finally
            {
                if (File.Exists(tempPath))
                    File.Delete(tempPath);
            }

            warning = null;
            return path;
        }
        catch (Exception e)
        {
            warning = $"dashboard not updated ({e.Message}) — runs are unaffected; plan files remain the truth";
            return null;
        }
    }

    private static IReadOnlyList<UnmergedApproval> CollectUnmergedApprovals(
        StatusReport report, GitWorkspace workspace)
    {
        var unmerged = new List<UnmergedApproval>();
        foreach (var entry in report.Plans)
        {
            foreach (var checkpoint in entry.Plan.Checkpoints)
            {
                if (checkpoint.Status != CheckpointStatus.Complete)
                    continue;
                var branch = CheckpointBranch.Name(entry.Plan.PlanId, checkpoint.Id);
                if (workspace.BranchExists(branch)
                    && workspace.CommitSubject(branch) is { } subject
                    && subject.StartsWith($"orca: {entry.Plan.PlanId}/{checkpoint.Id} attempt ", StringComparison.Ordinal)
                    && !workspace.IsAncestor(branch, entry.Plan.BaseBranch))
                {
                    unmerged.Add(new UnmergedApproval(
                        entry.Plan.PlanId, checkpoint.Id, branch, entry.Plan.BaseBranch));
                }
            }
        }

        return unmerged;
    }
}
